#!/usr/bin/env python3
"""Build complete EN/RU MSFS Markdown attachments (Python 3 + Pandoc).

    python3 scripts/build-markdown.py [--language all|en|ru]

The readable edition retains formulas, proofs, tables, references, bibliography
and diagram source. A separate source edition preserves every source byte for
auditing conversion. Neither edition changes the theoretical manuscripts.
"""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
THEOREMS = {"theorem", "lemma", "proposition", "corollary", "definition", "example", "remark", "convention"}


def digest(data):
    return hashlib.sha256(data).hexdigest()


def pandoc(args, content=None):
    result = subprocess.run(["pandoc", *args], input=content, text=True, capture_output=True)
    if result.returncode or result.stderr.strip():
        # A new reader warning requires attention; do not ship silent omissions.
        raise ValueError(f"Pandoc warning/error: {result.stderr.strip()}")
    return result.stdout


def nodes(value):
    if isinstance(value, dict):
        if "t" in value:
            yield value
        for child in value.values():
            yield from nodes(child)
    elif isinstance(value, list):
        for child in value:
            yield from nodes(child)


def fence(text, kind):
    mark = "`" * max(3, 1 + max((len(m) for m in re.findall(r"`+", text)), default=0))
    return f"{mark}{kind}\n{text}\n{mark}\n"


def source_inventory(text):
    uncommented = re.sub(r"(?<!\\)%[^\n]*", "", text)
    if re.search(r"\\(?:input|include|includegraphics|bibliography|addbibresource)\s*\{", uncommented):
        raise ValueError("New external manuscript dependency: flatten/include it explicitly before exporting")
    declarations = re.findall(r"\\newtheorem\{([^}]+)\}(?:\[([^]]+)\])?\{([^}]+)\}(?:\[([^]]+)\])?", uncommented)
    if {d[0] for d in declarations} != THEOREMS:
        raise ValueError("Changed theorem environment inventory; review numbering adapter")
    if not all((name == "theorem" and not shared and reset == "section") or
               (name != "theorem" and shared == "theorem" and not reset)
               for name, shared, _, reset in declarations):
        raise ValueError("Changed theorem numbering convention; refusing inaccurate generated numbers")
    if re.search(r"\\(?:setcounter|addtocounter|numberwithin|counterwithin|counterwithout|renewcommand)\s*\{(?:theorem|section|thetheorem|thesection)\}", uncommented):
        raise ValueError("Custom numbering is not covered by this exporter")
    section = theorem = 0
    appendix = False
    numbering = []
    event = re.compile(r"\\appendix\b|\\section(?=\s*\{)|\\begin\{(" + "|".join(sorted(THEOREMS)) + r")\}")
    for match in event.finditer(uncommented):
        if match[0].startswith("\\appendix"):
            section = theorem = 0
            appendix = True
        elif match[0].startswith("\\section"):
            section += 1
            theorem = 0
        else:
            theorem += 1
            prefix = chr(ord("A") + section - 1) if appendix else str(section)
            numbering.append((match[1], f"{prefix}.{theorem}"))
    labels = re.findall(r"\\label\{([^}]+)\}", uncommented)
    if len(labels) != len(set(labels)):
        raise ValueError("Duplicate manuscript labels")
    return {"numbering": numbering, "labels": labels,
        "environments": Counter(re.findall(r"\\begin\{([^}]+)\}", uncommented)),
        "bibliography_keys": re.findall(r"\\bibitem(?:\[[^]]*\])?\{([^}]+)\}", uncommented),
        "sections": len(re.findall(r"\\section\*?\s*\{", uncommented))}


def build(language, output_dir):
    path = ROOT / f"paper-{language}/paper.tex"
    raw = path.read_bytes()
    text = raw.decode("utf-8")
    inventory = source_inventory(text)
    ast = json.loads(pandoc([str(path), "--from=latex+raw_tex", "--to=json"]))
    original_math = [node["c"] for node in nodes(ast) if node["t"] == "Math"]
    theorem_nodes = [node for node in nodes(ast["blocks"]) if node["t"] == "Div" and
                     any(kind in THEOREMS for kind in node["c"][0][1])]
    if len(theorem_nodes) != len(inventory["numbering"]):
        raise ValueError("Theorem environments lost or duplicated by reader")
    for node, (kind, number) in zip(theorem_nodes, inventory["numbering"]):
        if kind not in node["c"][0][1]:
            raise ValueError("Theorem environment order differs from manuscript")
        first = node["c"][1][0]
        if first["t"] != "Para" or first["c"][0]["t"] != "Strong":
            raise ValueError("Unexpected Pandoc theorem heading")
        header = first["c"][0]["c"]
        if header[-1]["t"] != "Str" or not header[-1]["c"].isdigit():
            raise ValueError("Unexpected autogenerated theorem counter")
        header[-1]["c"] = number
    proof_count = sum(node["t"] == "Div" and "proof" in node["c"][0][1] for node in nodes(ast["blocks"]))
    if proof_count != inventory["environments"]["proof"]:
        raise ValueError("Proof environment count differs from manuscript")
    if sum(node["t"] == "Header" and node["c"][0] == 1 for node in nodes(ast["blocks"])) != inventory["sections"]:
        raise ValueError("Section count differs from manuscript")
    all_ast = json.dumps(ast, ensure_ascii=False)
    for label in inventory["labels"]:
        if label not in all_ast:
            raise ValueError(f"Manuscript label lost: {label}")
    for key in inventory["bibliography_keys"]:
        if key not in all_ast:
            raise ValueError(f"Bibliography entry lost: {key}")
    # Every unsupported environment is retained as explicit LaTeX source,
    # rather than a raw block that another Markdown renderer may omit.
    raw_blocks = 0
    for node in nodes(ast):
        if node["t"] == "Figure":
            attributes, caption, blocks = node["c"]
            # Pandoc's Markdown writer otherwise discards a Figure whose body
            # is TikZ source rather than an Image. Preserve body AND caption.
            node["t"] = "Div"
            node["c"] = [attributes, blocks + caption[1]]
        elif node["t"] == "RawBlock" and node["c"][0] in {"latex", "tex"}:
            content = node["c"][1]
            if content.strip() in {"\\maketitle", "\\newpage", "\\tableofcontents", "\\appendix"}:
                node.clear()
                node.update({"t": "Plain", "c": []})
            else:
                raw_blocks += 1
                node["t"] = "CodeBlock"
                node["c"] = [["", ["latex"], []], content]
        elif node["t"] == "RawInline" and node["c"][0] in {"latex", "tex"}:
            label = re.fullmatch(r"\\label\{([^}]+)\}", node["c"][1])
            reference = re.fullmatch(r"\\(?:ref|eqref|autoref)\{([^}]+)\}", node["c"][1])
            if label:
                node["c"] = ["html", f'<a id="{label[1]}"></a>']
            elif reference:
                node["t"] = "Link"
                node["c"] = [["", [], []], [{"t": "Str", "c": reference[1]}], ["#" + reference[1], "Source label"]]
    # Keep title/author/abstract in ordinary body Markdown, not hidden metadata.
    title = ast["meta"]["title"]
    title_inline = title["c"] if title["t"] == "MetaInlines" else title["c"][0]["c"]
    abstract = ast["meta"]["abstract"]
    abstract_blocks = abstract["c"] if abstract["t"] == "MetaBlocks" else [{"t": "Para", "c": abstract["c"]}]
    prefix = [{"t": "Header", "c": [1, ["msfs-document", [], []], title_inline]},
              {"t": "Para", "c": [{"t": "Str", "c": "Max Sereda"}]},
              {"t": "Header", "c": [2, ["abstract", [], []], [{"t": "Str", "c": "Abstract" if language == "en" else "Аннотация"}]]}]
    ast["blocks"] = prefix + abstract_blocks + ast["blocks"]
    ast["meta"] = {}
    if [node["c"] for node in nodes(ast) if node["t"] == "Math"] != original_math:
        # Metadata visitation precedes blocks in Pandoc JSON. Promoting only
        # abstract/title preserves all their math in the same relative order.
        before = Counter(json.dumps(m, sort_keys=True) for m in original_math)
        after = Counter(json.dumps(node["c"], sort_keys=True) for node in nodes(ast) if node["t"] == "Math")
        if before != after:
            raise ValueError("Formula inventory changed during transformation")
    readable = pandoc(["--from=json", "--to=markdown+raw_tex+raw_html-raw_attribute+tex_math_dollars", "--wrap=none"], json.dumps(ast))
    preamble = text.split("\\begin{document}", 1)[0]
    preface = (f"<!-- Complete MSFS export; source paper-{language}/paper.tex; SHA256 {digest(raw)} -->\n\n"
               "Export note: the full body, proofs and bibliography follow. Formula macros are expanded by Pandoc; "
               "the original preamble is included at the end. Unsupported diagrams and bibliography syntax are "
               "retained as LaTeX code. Cross-references name original source labels. Theorem numbering follows "
               "the manuscript's shared per-section counter. The companion source edition is byte-preserving.\n\n")
    readable = preface + readable + "\n# Original LaTeX preamble and notation\n\n" + fence(preamble, "latex")
    for label in inventory["labels"]:
        if label not in readable:
            raise ValueError(f"Label lost by writer: {label}")
    for key in inventory["bibliography_keys"]:
        if f"\\bibitem{{{key}}}" not in readable:
            raise ValueError(f"Bibliography entry lost by writer: {key}")
    for environment in ("tikzpicture", "tikzcd"):
        if readable.count("\\begin{" + environment + "}") != inventory["environments"][environment]:
            raise ValueError(f"Diagram source lost: {environment}")
    name = f"msfs-{language}"
    output = output_dir / f"{name}.md"
    output.write_text(readable)
    audit = output_dir / f"{name}-source.md"
    source_edition = f"# MSFS {language.upper()} — exact source edition\n\nSource: `paper-{language}/paper.tex`\n\nSHA256: `{digest(raw)}`\n\n" + fence(text, "latex")
    audit.write_text(source_edition)
    if source_edition.split("```latex\n", 1)[1].rsplit("\n```\n", 1)[0].encode() != raw:
        raise ValueError("Exact source edition round-trip failed")
    manifest = {"source": str(path.relative_to(ROOT)), "source_bytes": len(raw), "source_sha256": digest(raw),
        "pandoc": subprocess.check_output(["pandoc", "--version"], text=True).splitlines()[0],
        "readable_output": output.name, "readable_bytes": output.stat().st_size, "readable_sha256": digest(output.read_bytes()),
        "exact_source_output": audit.name, "exact_source_bytes": audit.stat().st_size, "exact_source_roundtrip": True,
        "source_sections": inventory["sections"], "source_numbered_statements": len(theorem_nodes), "proofs": proof_count,
        "math_nodes_preserved": len(original_math), "labels": inventory["labels"],
        "bibliography_keys": inventory["bibliography_keys"], "source_environments": dict(inventory["environments"]),
        "raw_blocks_preserved_as_latex_code": raw_blocks, "source_theorem_numbering": inventory["numbering"]}
    output.with_suffix(".manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    print(f"{output}: {output.stat().st_size:,} bytes; {len(theorem_nodes)} statements, {proof_count} proofs, {len(original_math)} formulas")
    print(f"{audit}: {audit.stat().st_size:,} bytes; exact source round-trip passed")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--language", choices=["all", "en", "ru"], default="all")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "output/markdown")
    args = parser.parse_args()
    if shutil.which("pandoc") is None:
        raise SystemExit("Pandoc is required (for example: brew install pandoc). No files changed.")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for language in ["en", "ru"] if args.language == "all" else [args.language]:
        build(language, args.output_dir)


if __name__ == "__main__":
    main()
